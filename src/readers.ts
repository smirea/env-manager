import type { OutputFormat } from './formats';
import type { CommentPrefix } from './metadata';
import type { EnvVarSchema } from './parser';

// What a format commits beside its values: the file that fails when the environment is incomplete.
interface Reader {
  // null: generated only when the config names a path.
  defaultPath: string | null;
  commentPrefix: CommentPrefix;
  // Lines that must come before the env-manager header.
  preamble: string;
  executable: boolean;
  render(schema: EnvVarSchema[]): string;
  matches(existing: string, rendered: string): boolean;
}

const TS_HEADER = `// AUTO-GENERATED by \`env-manager generate\` - do not edit
import { z } from 'zod';

const env = z.object({
`;

// Dotenv loaders read the schema's empty placeholders as '', so an empty value counts as unset:
// otherwise a required string, or a number coerced from '', would pass without a value.
const TS_FOOTER = `}).parse(Object.fromEntries(Object.entries(process.env).filter(([, value]) => value !== '')));

export default env;
`;

const ZOD_TYPES: Record<EnvVarSchema['type'], string> = {
  string: 'z.string()',
  int: 'z.coerce.number().int()',
  float: 'z.coerce.number()',
  bool: 'z.stringbool()',
  url: 'z.url()',
  email: 'z.email()',
  file: 'z.string()',
};

function zodField(s: EnvVarSchema): string {
  let chain = ZOD_TYPES[s.type];
  for (const v of s.validators) {
    if (v.kind === 'min') chain += `.min(${v.value})`;
    if (v.kind === 'max') chain += `.max(${v.value})`;
    if (v.kind === 'format') chain += `.regex(${v.pattern.toString()})`;
  }
  return `  ${s.name}: ${s.optional ? `${chain}.optional()` : chain},`;
}

// Never prints a value: the settings it checks are secrets and its output lands in build logs.
const CHECK_HEADER = `# AUTO-GENERATED by \`env-manager generate\` - do not edit
#
# Fails when a required setting is unset or a set one is malformed, before anything is built.
# Xcode exports build settings to a Run Script phase as environment variables, so run this as
# the target's first build phase. Any other caller passes the settings in its environment.

status=0

fail() {
  echo "error: env-manager: $1" >&2
  status=1
}

check() {
  name=$1 need=$2 kind=$3 min=\${4-} max=\${5-}
  eval "value=\\\${$name-}"
  if [ -z "$value" ]; then
    if [ "$need" = required ]; then fail "$name is not set"; fi
    return 0
  fi
  case $kind in
    int)
      case \${value#[+-]} in
        '' | *[!0-9]*) fail "$name is not an integer"; return 0 ;;
      esac ;;
    float)
      if ! printf '%s\\n' "$value" | grep -Eq '^[+-]?([0-9]+\\.?[0-9]*|\\.[0-9]+)$'; then fail "$name is not a number"; return 0; fi ;;
    bool)
      case $(printf '%s' "$value" | tr '[:upper:]' '[:lower:]') in
        true | false | 1 | 0 | yes | no | on | off) ;;
        *) fail "$name is not a boolean" ;;
      esac ;;
    url)
      case $value in
        [A-Za-z]*://?*) ;;
        *) fail "$name is not a URL" ;;
      esac ;;
    email)
      case $value in
        ?*@?*.?*) ;;
        *) fail "$name is not an email address" ;;
      esac ;;
  esac
  if [ -n "$min" ] && awk -v value="$value" -v min="$min" 'BEGIN { exit !(value + 0 < min + 0) }'; then fail "$name is below $min"; fi
  if [ -n "$max" ] && awk -v value="$value" -v max="$max" 'BEGIN { exit !(value + 0 > max + 0) }'; then fail "$name is above $max"; fi
}

match() {
  eval "value=\\\${$1-}"
  if [ -n "$value" ] && ! printf '%s\\n' "$value" | grep -E$3q -- "$2"; then fail "$1 does not match $2"; fi
}

`;

const CHECK_FOOTER = `
exit $status
`;

// grep -E has no \\d, \\w, lookarounds or lazy quantifiers, and a pattern it reads differently
// would pass or fail the wrong values.
function portablePattern(pattern: RegExp): { source: string; flags: string } | null {
  if (!/^i?$/.test(pattern.flags)) return null;
  if (/\\[A-Za-z0-9]|\(\?|[*+?}]\?/.test(pattern.source)) return null;
  return { source: pattern.source.replaceAll('\\/', '/'), flags: pattern.flags };
}

function quote(value: string): string {
  return `'${value.replaceAll("'", `'\\''`)}'`;
}

function checkLines(s: EnvVarSchema): string[] {
  const min = s.validators.find(v => v.kind === 'min')?.value;
  const max = s.validators.find(v => v.kind === 'max')?.value;
  const bounds = max === undefined ? (min === undefined ? '' : ` ${min}`) : ` ${min === undefined ? "''" : min} ${max}`;
  const lines = [`check ${s.name} ${s.optional ? 'optional' : 'required'} ${s.type}${bounds}`];
  for (const v of s.validators) {
    if (v.kind !== 'format') continue;
    const portable = portablePattern(v.pattern);
    lines.push(portable
      ? `match ${s.name} ${quote(portable.source)} ${quote(portable.flags)}`
      : `# ${s.name}: ${v.pattern} is not checked here, because grep -E cannot run that pattern.`);
  }
  return lines;
}

// Formatters only touch whitespace, quotes, semicolons, commas and parens, so a reader that
// still differs after dropping those was edited by hand.
function formatterFingerprint(content: string): string {
  return content.replace(/[\s'"`;,()]/g, '');
}

export const READERS = {
  ts: {
    defaultPath: 'src/env.ts',
    commentPrefix: '//',
    preamble: '',
    executable: false,
    render: schema => TS_HEADER + schema.map(zodField).join('\n') + '\n' + TS_FOOTER,
    matches: (existing, rendered) => formatterFingerprint(existing) === formatterFingerprint(rendered),
  },
  swift: {
    defaultPath: null,
    commentPrefix: '#',
    preamble: '#!/bin/sh\n',
    executable: true,
    render: schema => CHECK_HEADER + schema.flatMap(checkLines).join('\n') + '\n' + CHECK_FOOTER,
    matches: (existing, rendered) => existing === rendered,
  },
} satisfies Record<OutputFormat, Reader>;
