import { describe, expect, test } from 'bun:test';
import { mkdir, mkdtemp, readdir, readFile, rm, stat, symlink, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { generateCommand } from './generate';

async function withTempDir<T>(fn: (dir: string) => Promise<T>): Promise<T> {
  const dir = await mkdtemp(path.join(os.tmpdir(), 'env-manager-ts-'));
  try {
    await writeFile(path.join(dir, 'package.json'), '{}\n');
    return await fn(dir);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

const ENV_CONTENT = `# env-manager: test-project | 2025-01-01T00:00:00Z\n\nFOO=bar # {optional string}\n`;

describe('generate command', () => {
  test('the reader maps each schema type to its zod validator', async () => {
    await withTempDir(async (dir) => {
      await writeFile(path.join(dir, '.env'), [
        '# env-manager: test-project',
        '',
        'CALLBACK= # {url}',
        'ADMIN= # {optional email}',
        'DEBUG= # {optional bool}',
        'PORT=3000 # {int:min(1),max(65535)}',
        'RATE= # {float}',
        'TOKEN= # {string:format(/^sk-/i)}',
        'CERT= # {file}',
        '',
      ].join('\n'));
      await generateCommand({ project: 'test-project', cwd: dir }, 'env.ts');
      expect(await readFile(path.join(dir, 'env.ts'), 'utf8')).toBe(`// env-manager: test-project | v1
// AUTO-GENERATED by \`env-manager generate\` - do not edit
import { z } from 'zod';

const env = z.object({
  CALLBACK: z.url(),
  ADMIN: z.email().optional(),
  DEBUG: z.stringbool().optional(),
  PORT: z.coerce.number().int().min(1).max(65535),
  RATE: z.coerce.number(),
  TOKEN: z.string().regex(/^sk-/i),
  CERT: z.string(),
}).parse(Object.fromEntries(Object.entries(process.env).filter(([, value]) => value !== '')));

export default env;
`);
    });
  });

  test('a generated reader treats an empty value as unset: an optional one reads as undefined and a required one fails by name', async () => {
    await withTempDir(async (dir) => {
      await writeFile(path.join(dir, '.env'), '# env-manager: test-project\n\nCALLBACK= # {optional url}\nDEBUG= # {optional bool}\nNAME= # {string}\nPORT= # {int}\n');
      await generateCommand({ project: 'test-project', cwd: dir }, 'env.ts');
      await symlink(path.resolve(import.meta.dir, '../../node_modules'), path.join(dir, 'node_modules'));
      const names = ['CALLBACK', 'DEBUG', 'NAME', 'PORT'];
      const previous = Object.fromEntries(names.map(name => [name, process.env[name]]));
      const read = (env: Record<string, string>, run: string) => {
        Object.assign(process.env, env);
        return import(`${path.join(dir, 'env.ts')}?${run}`).then(module => module.default);
      };
      try {
        expect(await read({ CALLBACK: '', DEBUG: '', NAME: 'app', PORT: '3000' }, 'set')).toEqual({ NAME: 'app', PORT: 3000 });
        const blank = read({ CALLBACK: '', DEBUG: '', NAME: '', PORT: '' }, 'blank');
        await expect(blank).rejects.toThrow('NAME');
        await expect(blank).rejects.toThrow('PORT');
      } finally {
        for (const [name, value] of Object.entries(previous)) {
          if (value === undefined) delete process.env[name];
          else process.env[name] = value;
        }
      }
    });
  });

  test('a reader path is stored in .env and reused, and a different one replaces it only with --force', async () => {
    await withTempDir(async (dir) => {
      const ctx = { project: 'test-project', cwd: dir };
      await writeFile(path.join(dir, '.env'), ENV_CONTENT);
      await generateCommand(ctx, 'custom/env.ts');
      expect(await readFile(path.join(dir, '.env'), 'utf8')).toContain('# env-manager ts: custom/env.ts\n');
      await rm(path.join(dir, 'custom'), { recursive: true });
      await generateCommand(ctx);
      expect(await readFile(path.join(dir, 'custom/env.ts'), 'utf8')).toContain('FOO: z.string().optional(),');

      await expect(generateCommand(ctx, 'new.ts')).rejects.toThrow('--force');
      expect(await Bun.file(path.join(dir, 'new.ts')).exists()).toBe(false);
      await generateCommand(ctx, 'new.ts', { force: true });
      expect(await readFile(path.join(dir, 'new.ts'), 'utf8')).toContain('FOO: z.string().optional(),');
      expect(await readFile(path.join(dir, '.env'), 'utf8')).toContain('# env-manager ts: new.ts\n');
    });
  });

  test('a swift check script fails, naming each variable, when a required setting is unset or a set one is malformed, and never prints a value', async () => {
    await withTempDir(async (dir) => {
      await writeFile(path.join(dir, '.env'), [
        '# env-manager: test-project',
        '# env-manager target: ios format=swift generate=Config/check-env.sh',
        '',
        '# env-manager targets: ios',
        'API_URL=http://127.0.0.1:3000 # {url}',
        'OWNER_TOKEN= # {string:format(/^tok_/)}',
        'PORT=3000 # {int:min(1),max(65535)}',
        'SENTRY_ENVIRONMENT= # {optional string:format(/^(production|development)$/)}',
        'BUILD_TAG= # {optional string:format(/^\\d+$/)}',
        '',
      ].join('\n'));
      await generateCommand({ project: 'test-project', cwd: dir });
      const script = path.join(dir, 'ios/Config/check-env.sh');
      const content = await readFile(script, 'utf8');
      expect(content.split('\n').slice(0, 4)).toEqual([
        '#!/bin/sh',
        '# env-manager: test-project | v1',
        '# env-manager target: ios',
        '# env-manager root: ../..',
      ]);
      expect(content).toContain('# BUILD_TAG: /^\\d+$/ is not checked here');
      expect((await stat(script)).mode & 0o111).toBe(0o111);

      const run = (env: Record<string, string>) => {
        const result = Bun.spawnSync([script], { env: { PATH: process.env.PATH, ...env } });
        return { code: result.exitCode, errors: result.stderr.toString().trim().split('\n').filter(Boolean) };
      };
      const good = { API_URL: 'https://example.com', OWNER_TOKEN: 'tok_secret', PORT: '8080' };
      expect(run(good)).toEqual({ code: 0, errors: [] });
      expect(run({ ...good, SENTRY_ENVIRONMENT: 'production' })).toEqual({ code: 0, errors: [] });
      expect(run({ SENTRY_ENVIRONMENT: 'staging', API_URL: 'example.com', OWNER_TOKEN: 'hunter2', PORT: '70000' })).toEqual({
        code: 1,
        errors: [
          'error: env-manager: API_URL is not a URL',
          'error: env-manager: OWNER_TOKEN does not match ^tok_',
          'error: env-manager: PORT is above 65535',
          'error: env-manager: SENTRY_ENVIRONMENT does not match ^(production|development)$',
        ],
      });
      expect(run({ PORT: 'abc' })).toEqual({
        code: 1,
        errors: [
          'error: env-manager: API_URL is not set',
          'error: env-manager: OWNER_TOKEN is not set',
          'error: env-manager: PORT is not an integer',
        ],
      });

      await generateCommand({ project: 'test-project', cwd: dir });
      expect(await readFile(script, 'utf8')).toBe(content);
    });
  });

  test('an output is rewritten only when its content drifts from the render, so formatter-only edits survive and hand edits are replaced', async () => {
    await withTempDir(async (dir) => {
      const ctx = { project: 'test-project', cwd: dir };
      const read = (name: string) => readFile(path.join(dir, name), 'utf8');
      await writeFile(path.join(dir, '.env'), '# env-manager: test-project | 2025-01-01T00:00:00Z\n\nFOO=bar # {string}\n');
      await generateCommand(ctx, 'env.ts');
      const reader = await read('env.ts');
      expect(reader.split('\n')[0]).toBe('// env-manager: test-project | v1');
      expect(await read('.env')).toBe('# env-manager: test-project | 2025-01-01T00:00:00Z\n# env-manager ts: env.ts\n\nFOO=bar # {string}\n');
      const local = await read('.env.local');
      expect(local.split('\n').slice(0, 3).map(line => line.replace(/[0-9a-f]{16}$/, '<hash>'))).toEqual([
        '# env-manager: test-project | v1',
        '# env-manager output: .env.local v1 <hash>',
        '# env-manager output: env.ts v1 <hash>',
      ]);

      const formatted = reader.replaceAll("'", '"').replace('  FOO: z.string(),', '    FOO: z.string(),');
      await writeFile(path.join(dir, 'env.ts'), formatted);
      await generateCommand(ctx);
      expect(await read('env.ts')).toBe(formatted);
      expect(await read('.env.local')).toBe(local);

      await writeFile(path.join(dir, 'env.ts'), formatted.replace('z.string()', 'z.url()'));
      await generateCommand(ctx);
      expect(await read('env.ts')).toBe(reader);
      expect(await read('.env.local')).toBe(local);

      await writeFile(path.join(dir, '.env'), '# env-manager: test-project\n# env-manager ts: env.ts\n\nFOO=bar # {string}\nBAR=1 # {int}\n');
      await generateCommand(ctx);
      const regenerated = await read('env.ts');
      expect(regenerated.split('\n')[0]).toBe('// env-manager: test-project | v2');
      expect(regenerated).toContain('  BAR: z.coerce.number().int(),');
    });
  });

  test('a pulled reader that matches its render keeps its version, whatever the local record holds', async () => {
    await withTempDir(async (dir) => {
      const ctx = { project: 'test-project', cwd: dir };
      const read = (name: string) => readFile(path.join(dir, name), 'utf8');
      await writeFile(path.join(dir, '.env'), '# env-manager: test-project\n# env-manager generate: env.ts\n\nFOO=bar # {string}\n');
      await generateCommand(ctx);
      expect((await read('env.ts')).split('\n')[0]).toBe('// env-manager: test-project | v1');

      // What `git pull` brings: a schema with a new variable and the reader someone else generated for it.
      const pulled = (await read('env.ts'))
        .replace('| v1', '| v2')
        .replace('  FOO: z.string(),', '  FOO: z.string(),\n  BAR: z.coerce.number().int(),');
      await writeFile(path.join(dir, '.env'), '# env-manager: test-project\n# env-manager generate: env.ts\n\nFOO=bar # {string}\nBAR=1 # {int}\n');
      await writeFile(path.join(dir, 'env.ts'), pulled);

      await generateCommand(ctx);
      expect(await read('env.ts')).toBe(pulled);
      expect(await read('.env.local')).toMatch(/^# env-manager output: env\.ts v2 [0-9a-f]{16}$/m);

      await generateCommand(ctx);
      expect(await read('env.ts')).toBe(pulled);
    });
  });

  test('each target child carries its own version', async () => {
    await withTempDir(async (dir) => {
      const ctx = { project: 'test-project', cwd: dir };
      const read = (name: string) => readFile(path.join(dir, name), 'utf8');
      await writeFile(path.join(dir, '.env'), [
        '# env-manager: test-project',
        '# env-manager target: client format=ts path=.env.local',
        '# env-manager target: server format=ts path=.env.local',
        '# env-manager targets: client',
        'FOO= # {string}',
        '# env-manager targets: server',
        'BAR= # {string}',
        '',
      ].join('\n'));
      await writeFile(path.join(dir, '.env.local'), 'FOO=one\nBAR=one\n');
      await generateCommand(ctx);
      const client = await read('client/.env.local');
      expect(client.split('\n')[0]).toBe('# env-manager: test-project | v1');
      expect(client).toContain("FOO='one' # {string}");

      const formatted = client.replace("FOO='one'", 'FOO="one"');
      await writeFile(path.join(dir, 'client/.env.local'), formatted);
      await writeFile(path.join(dir, '.env.local'), (await read('.env.local')).replace('BAR=one', 'BAR=two'));
      await generateCommand(ctx);
      expect(await read('client/.env.local')).toBe(formatted);
      const server = await read('server/.env.local');
      expect(server.split('\n')[0]).toBe('# env-manager: test-project | v2');
      expect(server).toContain("BAR='two' # {string}");
      expect((await read('.env.local')).split('\n')[0]).toBe('# env-manager: test-project | v2');
    });
  });

  test('switching environments never rewrites a reader', async () => {
    await withTempDir(async (dir) => {
      const ctx = { project: 'test-project', cwd: dir };
      const read = (name: string) => readFile(path.join(dir, name), 'utf8');
      await writeFile(path.join(dir, '.env'), [
        '# env-manager: test-project',
        '# env-manager target: client format=ts generate=src/env.ts',
        '# env-manager targets: client',
        'FOO= # {string}',
        '',
      ].join('\n'));
      await writeFile(path.join(dir, '.env.local'), '# env-manager env: staging\nFOO=one\n');
      await generateCommand(ctx);
      const reader = await read('client/src/env.ts');
      expect(reader).not.toContain('env-manager env:');

      await writeFile(path.join(dir, '.env.local'), (await read('.env.local')).replace('env: staging', 'env: production'));
      await generateCommand(ctx);
      expect(await read('client/src/env.ts')).toBe(reader);
      expect(await read('client/.env.local')).toContain('# env-manager env: production');
    });
  });

  test('a child left over from another environment is regenerated even when its version is ahead', async () => {
    await withTempDir(async (dir) => {
      const ctx = { project: 'test-project', cwd: dir };
      const read = (name: string) => readFile(path.join(dir, name), 'utf8');
      await writeFile(path.join(dir, '.env'), '# env-manager: test-project\n# env-manager target: server format=ts path=.env.local\n# env-manager targets: server\nAPP_ENV=development # {string}\n');
      await writeFile(path.join(dir, '.env.local'), '# env-manager env: dev\n');
      await generateCommand(ctx);
      const devRoot = await read('.env.local');
      const devChild = await read('server/.env.local');

      await writeFile(path.join(dir, '.env.local'), devRoot.replace('env: dev', 'env: prod') + 'APP_ENV=production\n');
      await generateCommand(ctx);
      expect(await read('server/.env.local')).toContain("# env-manager: test-project | v2\n# env-manager target: server\n# env-manager root: ..\n# env-manager env: prod\nAPP_ENV='production'");

      await writeFile(path.join(dir, '.env.local'), devRoot);
      await generateCommand(ctx);
      expect(await read('server/.env.local')).toBe(devChild);
      expect(await read('.env.local')).toBe(devRoot);
    });
  });

  test('values children are compared by value, so a change of only whitespace or commas still regenerates them', async () => {
    await withTempDir(async (dir) => {
      const ctx = { project: 'test-project', cwd: dir };
      const read = (name: string) => readFile(path.join(dir, name), 'utf8');
      await writeFile(path.join(dir, '.env'), [
        '# env-manager: test-project',
        '# env-manager target: web format=ts path=.env.local',
        '# env-manager target: ios format=swift path=Config/LocalSecrets.xcconfig',
        '# env-manager targets: *',
        'NAME= # {string}',
        '',
      ].join('\n'));
      for (const [older, newer] of [['a b', 'ab'], ['x,y', 'xy']]) {
        await writeFile(path.join(dir, '.env.local'), `NAME='${older}'\n`);
        await generateCommand(ctx);
        const olderRoot = await read('.env.local');
        const olderWeb = await read('web/.env.local');
        const olderIos = await read('ios/Config/LocalSecrets.xcconfig');
        expect(olderWeb).toContain(`NAME='${older}' # {string}`);
        expect(olderIos).toContain(`NAME = ${older}\n`);

        await writeFile(path.join(dir, '.env.local'), olderRoot.replace(`NAME='${older}'`, `NAME='${newer}'`));
        await generateCommand(ctx);
        expect(await read('web/.env.local')).toContain(`NAME='${newer}' # {string}`);

        await writeFile(path.join(dir, '.env.local'), olderRoot);
        await generateCommand(ctx);
        expect(await read('web/.env.local')).toBe(olderWeb);
        expect(await read('ios/Config/LocalSecrets.xcconfig')).toBe(olderIos);
      }
    });
  });

  test('a target child holds only the variables selected for it, a reader holds no values, and the root values file keeps what was written', async () => {
    await withTempDir(async (dir) => {
      const ctx = { project: 'mono', cwd: dir };
      const read = (name: string) => readFile(path.join(dir, name), 'utf8');
      await writeFile(path.join(dir, '.env'), [
        '# env-manager: mono',
        '# env-manager target: ios format=swift',
        '# env-manager target: client format=ts path=.env',
        '# env-manager target: server format=ts path=config/.env.local',
        '# env-manager targets: *',
        'API_URL=https://example.com # {url}',
        '# env-manager targets: client',
        'CLIENT_KEY= # {string}',
        '# env-manager targets: server',
        'SERVER_KEY= # {string}',
        '',
      ].join('\n'));
      const source = '# env-manager env: staging\nCLIENT_KEY=client-secret\nSERVER_KEY=server-secret\n';
      await writeFile(path.join(dir, '.env.local'), source);

      await generateCommand(ctx, undefined, { target: 'client' });
      expect(await Bun.file(path.join(dir, 'server/config/.env.local')).exists()).toBe(false);
      expect(await Bun.file(path.join(dir, 'ios/Config/LocalSecrets.xcconfig')).exists()).toBe(false);

      await generateCommand(ctx);
      const client = await read('client/.env');
      expect(client).toContain("CLIENT_KEY='client-secret'");
      expect(client).not.toContain('SERVER_KEY');
      expect(client).toContain('# env-manager target: client\n# env-manager root: ..\n# env-manager env: staging\n');
      const server = await read('server/config/.env.local');
      expect(server).toContain("SERVER_KEY='server-secret'");
      expect(server).not.toContain('CLIENT_KEY');
      const ios = await read('ios/Config/LocalSecrets.xcconfig');
      expect(ios).toContain('API_URL = https:/$()/example.com');
      expect(ios).not.toContain('_KEY');
      for (const reader of ['client/src/env.ts', 'server/src/env.ts']) {
        const content = await read(reader);
        expect(content).not.toContain('client-secret');
        expect(content).not.toContain('server-secret');
      }
      const root = (await read('.env.local')).split('\n').filter(line => !line.startsWith('# env-manager: ') && !line.startsWith('# env-manager output: '));
      expect(root.join('\n')).toBe(source);
    });
  });

  test('generation writes nothing when any planned output collides, belongs to another project, escapes through a symlink, or sits under a file', async () => {
    await withTempDir(async (dir) => {
      const ctx = { project: 'mono', cwd: dir };
      const valid = '# env-manager: mono\n# env-manager target: client format=ts\n# env-manager target: server format=ts\n# env-manager targets: *\nPORT=3000 # {int}\n';
      const nothingWritten = async () => {
        expect(await Bun.file(path.join(dir, '.env.local')).exists()).toBe(false);
        expect(await Bun.file(path.join(dir, 'client/src/env.ts')).exists()).toBe(false);
      };

      await writeFile(path.join(dir, '.env'), valid.replace('target: server format=ts', 'target: server format=ts path=src/env.ts'));
      await expect(generateCommand(ctx)).rejects.toThrow();
      await nothingWritten();

      await writeFile(path.join(dir, '.env'), valid);
      await mkdir(path.join(dir, 'server'));
      await writeFile(path.join(dir, 'server/.env.local'), '# env-manager: another-project\n');
      await expect(generateCommand(ctx)).rejects.toThrow();
      await nothingWritten();

      await rm(path.join(dir, 'server'), { recursive: true });
      const outside = await mkdtemp(path.join(os.tmpdir(), 'env-manager-outside-'));
      await symlink(outside, path.join(dir, 'server'));
      try {
        await expect(generateCommand(ctx)).rejects.toThrow();
        await nothingWritten();
        expect(await readdir(outside)).toEqual([]);
      } finally {
        await rm(path.join(dir, 'server'));
        await rm(outside, { recursive: true, force: true });
      }

      await mkdir(path.join(dir, 'server'));
      await writeFile(path.join(dir, 'server/src'), 'not a directory');
      await expect(generateCommand(ctx)).rejects.toThrow();
      await nothingWritten();

      await rm(path.join(dir, 'server'), { recursive: true });
      await generateCommand(ctx);
      expect(await Bun.file(path.join(dir, 'client/src/env.ts')).exists()).toBe(true);
    });
  });

  describe('.env.override', () => {
    const MONOREPO = [
      '# env-manager: test-project',
      '# env-manager target: client format=ts path=.env.local',
      '# env-manager targets: client',
      'PORT=3000 # {int:min(1)}',
      'HOST= # {optional string}',
      '',
    ].join('\n');

    test('overrides apply to target outputs and never to the root values file', async () => {
      await withTempDir(async (dir) => {
        const ctx = { project: 'test-project', cwd: dir };
        const read = (name: string) => readFile(path.join(dir, name), 'utf8');
        await writeFile(path.join(dir, '.env'), MONOREPO);
        await writeFile(path.join(dir, '.env.local'), 'PORT=3000\n');
        await writeFile(path.join(dir, '.env.override'), 'PORT=4100\nHOST=wt.localhost\n');
        await generateCommand(ctx);
        expect(await read('client/.env.local')).toContain("PORT=4100 # {int:min(1)}");
        expect(await read('client/.env.local')).toContain("HOST='wt.localhost'");
        expect(await read('.env.local')).toContain('PORT=3000\n');
        expect(await read('.env.local')).not.toContain('4100');

        const child = await read('client/.env.local');
        await generateCommand(ctx);
        expect(await read('client/.env.local')).toBe(child);

        await writeFile(path.join(dir, '.env.override'), 'PORT=4200\n');
        await generateCommand(ctx);
        expect(await read('client/.env.local')).toContain('PORT=4200 ');
      });
    });

    test('an override must be a declared variable with a valid value, and single-project setups reject the file', async () => {
      await withTempDir(async (dir) => {
        const ctx = { project: 'test-project', cwd: dir };
        await writeFile(path.join(dir, '.env'), MONOREPO);
        await writeFile(path.join(dir, '.env.local'), 'PORT=3000\n');
        const overridePath = path.join(dir, '.env.override');
        await writeFile(overridePath, 'PORT=4100\nPROT=1\n');
        await expect(generateCommand(ctx)).rejects.toThrow(`${overridePath}:2:`);
        await writeFile(overridePath, 'PORT=0\n');
        await expect(generateCommand(ctx)).rejects.toThrow(`${overridePath}:1:`);
        expect(await Bun.file(path.join(dir, 'client/.env.local')).exists()).toBe(false);

        await writeFile(path.join(dir, '.env'), ENV_CONTENT);
        await writeFile(overridePath, 'FOO=x\n');
        await expect(generateCommand(ctx, 'env.ts')).rejects.toThrow(`${overridePath}:1:`);
      });
    });
  });
});
